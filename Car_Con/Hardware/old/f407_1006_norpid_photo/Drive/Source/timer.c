/***
	*************************************************************************************************
	*	@version V1.0
	*	@brief   TIM2 微秒时基
   *************************************************************************************************
   *  @description
	*
>>>>> 文件说明：
	*
	*  1. TIM2 配置为 1MHz 的 32 位自由运行计数器 (APB1定时器时钟 84MHz, 84分频)
	*  2. 提供微秒时间戳 Get_Us() 与微秒延时 Delay_us()
	*  3. 计数器约 4294 秒回绕一次, 延时与差值计算均采用无符号减法, 可容忍回绕
	*
	************************************************************************************************
***/

#include "timer.h"

/*************************************************************************************************
*	函 数 名:	Timer_Init
*
*	函数功能:	初始化 TIM2 为 1MHz 自由运行计数器
*
*************************************************************************************************/
void Timer_Init(void)
{
	TIM_TimeBaseInitTypeDef TIM_TimeBaseStructure;

	RCC_APB1PeriphClockCmd(RCC_APB1Periph_TIM2, ENABLE);	// 使能TIM2时钟

	TIM_TimeBaseStructure.TIM_Prescaler     = 84 - 1;				// 84MHz -> 1MHz
	TIM_TimeBaseStructure.TIM_CounterMode   = TIM_CounterMode_Up;	// 向上计数
	TIM_TimeBaseStructure.TIM_Period        = 0xFFFFFFFF;			// 32位最大周期
	TIM_TimeBaseStructure.TIM_ClockDivision = TIM_CKD_DIV1;
	TIM_TimeBaseInit(TIM2, &TIM_TimeBaseStructure);

	TIM_Cmd(TIM2, ENABLE);	// 启动计数器
}

/*************************************************************************************************
*	函 数 名:	Get_Us
*
*	返 回 值:	系统运行的微秒数 (约4294秒回绕)
*
*	函数功能:	读取微秒时间戳
*
*************************************************************************************************/
uint32_t Get_Us(void)
{
	return TIM2->CNT;
}

/*************************************************************************************************
*	函 数 名:	Get_Ms
*
*	返 回 值:	系统运行的毫秒数
*
*************************************************************************************************/
uint32_t Get_Ms(void)
{
	return TIM2->CNT / 1000;
}

/*************************************************************************************************
*	函 数 名:	Delay_us
*
*	入口参数:	nUs - 延时时间, 单位us
*
*	函数功能:	微秒级阻塞延时
*
*************************************************************************************************/
void Delay_us(uint32_t nUs)
{
	uint32_t start = TIM2->CNT;

	while ((uint32_t)(TIM2->CNT - start) < nUs);	// 无符号减法, 可容忍计数器回绕
}
